package logic

import (
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/distribution/reference"
	"k8s.io/apimachinery/pkg/util/validation"
)

const (
	executionNamespace       = "default"
	ActionBuild              = "build"
	ActionDeploy             = "deploy"
	SourceOriginal           = "original"
	SourceTask               = "task"
	WorkflowBuildActorPrefix = "zpk-workflow-"
)

type Config struct {
	Namespace string `json:"namespace"`
	Tasks     []Task `json:"tasks"`
}
type Task struct {
	ID                string `json:"id"`
	Name              string `json:"name"`
	Stage             int    `json:"stage"`
	Action            string `json:"action"`
	DeployType        int    `json:"deploy_type"`
	MatchType         int    `json:"match_type"`
	TagName           string `json:"tag_name"`
	Source            string `json:"source"`
	SourceTask        string `json:"source_task"`
	Dockerfile        string `json:"dockerfile"`
	TagSuffix         string `json:"tag_suffix"`
	K8sConfig         string `json:"k8s_config,omitempty"`
	K8sNamespace      string `json:"k8s_namespace"`
	K8sControllerType string `json:"k8s_controller_type"`
	K8sAppName        string `json:"k8s_app_name"`
	K8sContainerName  string `json:"k8s_container_name"`
}

func (c Config) Validate() error {
	if c.Namespace != executionNamespace {
		return errors.New("工作流固定在 default 命名空间执行")
	}
	if len(c.Tasks) > 32 {
		return errors.New("每个工作流最多配置 32 个任务")
	}
	totalDockerfileBytes := 0
	tasksByID := map[string]Task{}
	for _, task := range c.Tasks {
		if len(task.ID) > 40 || len(validation.IsDNS1123Label(task.ID)) != 0 {
			return errors.New("任务标识无效")
		}
		if _, ok := tasksByID[task.ID]; ok {
			return errors.New("任务标识不能重复")
		}
		tasksByID[task.ID] = task
		if strings.TrimSpace(task.Name) == "" || len(task.Name) > 120 || task.Stage < 1 || task.Stage > 1000 {
			return errors.New("任务名称或执行顺序无效")
		}
		if task.DeployType != 1 && task.DeployType != 2 {
			return errors.New("触发方式无效")
		}
		if strings.TrimSpace(task.TagName) == "" || len(task.TagName) > 1024 {
			return errors.New("请填写版本名称匹配条件")
		}
		if task.DeployType == 2 && task.MatchType != 1 && task.MatchType != 2 {
			return errors.New("匹配方式无效")
		}
		if task.DeployType == 2 && task.MatchType == 2 {
			if _, err := regexp.Compile(task.TagName); err != nil {
				return fmt.Errorf("版本正则无效: %w", err)
			}
		}
		if task.Source != SourceOriginal && task.Source != SourceTask {
			return errors.New("镜像来源无效")
		}
		switch task.Action {
		case ActionBuild:
			totalDockerfileBytes += len(task.Dockerfile)
			if totalDockerfileBytes > 256*1024 {
				return errors.New("工作流 Dockerfile 总长度不能超过 256 KiB")
			}
			if strings.TrimSpace(task.Dockerfile) == "" || len(task.Dockerfile) > 32768 {
				return errors.New("Dockerfile 指令为空或超过 32 KiB")
			}
			// FROM is generated by the workflow. Disallow parser directives and extra stages.
			for _, line := range strings.Split(task.Dockerfile, "\n") {
				fields := strings.Fields(strings.TrimSpace(line))
				if len(fields) == 0 {
					continue
				}
				if strings.HasPrefix(fields[0], "#") {
					if strings.HasPrefix(strings.ToLower(strings.TrimSpace(line)), "#syntax=") {
						return errors.New("不支持自定义 Dockerfile frontend")
					}
					continue
				}

				if strings.EqualFold(fields[0], "FROM") || strings.EqualFold(fields[0], "ONBUILD") || strings.EqualFold(fields[0], "ADD") || strings.EqualFold(fields[0], "COPY") {
					return errors.New("重构指令不支持 FROM、ONBUILD、ADD、COPY")
				}
			}
			if _, err := reference.WithTag(mustRepository(), "tag"+task.TagSuffix); err != nil || len(task.TagSuffix) > 100 {
				return errors.New("目标 tag 后缀无效")
			}
		case ActionDeploy:
			if !slices.Contains([]string{"deployments", "daemonsets", "statefulsets"}, task.K8sControllerType) || len(validation.IsDNS1123Subdomain(task.K8sAppName)) != 0 || len(validation.IsDNS1123Label(task.K8sNamespace)) != 0 {
				return errors.New("部署目标无效")
			}
			if task.K8sContainerName == "" {
				return errors.New("请选择部署容器")
			}
			for _, name := range strings.Split(task.K8sContainerName, ",") {
				if len(validation.IsDNS1123Label(name)) != 0 {
					return errors.New("容器名称无效")
				}
			}
			if task.K8sConfig != "" {
				if err := (Deploy{}).ValidateK8sConfig(task.K8sConfig); err != nil {
					return err
				}
			}

		default:
			return errors.New("执行动作无效")
		}
	}
	for _, task := range c.Tasks {
		if task.Source == SourceTask {
			sourceBuildTask, ok := tasksByID[task.SourceTask]
			if ok && !task.SameTrigger(sourceBuildTask) {
				return errors.New("镜像来源任务的触发方式、匹配方式和版本条件必须相同")
			}
			if !ok || sourceBuildTask.Action != ActionBuild || sourceBuildTask.Stage >= task.Stage {
				return errors.New("镜像来源必须是前面阶段的构建任务")
			}
		}
	}
	return nil
}

// SameTrigger compares configured conditions, not whether patterns overlap for one event.
// MatchType is unused for version updates, whose tags always use exact matching.
func (t Task) SameTrigger(other Task) bool {
	return t.DeployType == other.DeployType &&
		(t.DeployType != 2 || t.MatchType == other.MatchType) &&
		strings.TrimSpace(t.TagName) == strings.TrimSpace(other.TagName)
}

func (t Task) Matches(tag string, eventType int) bool {
	if t.DeployType != eventType {
		return false
	}
	if eventType == 2 && t.MatchType == 2 {
		re, err := regexp.Compile(t.TagName)
		return err == nil && re.MatchString(tag)
	}
	for _, item := range strings.Split(t.TagName, ",") {
		item = strings.TrimSpace(item)
		if item != "" && (item == tag || (eventType == 2 && t.MatchType == 1 && strings.HasPrefix(tag, item))) {
			return true
		}
	}
	return false
}

// Select validates references after matching; a missing predecessor never falls back silently.
func (c Config) SelectMatchingTasks(tag string, eventType int) ([]Task, error) {
	matchedTasks := []Task{}
	matchedTasksByID := map[string]Task{}
	outputs := map[string]Task{}
	for _, task := range c.Tasks {
		if !task.Matches(tag, eventType) {
			continue
		}
		matchedTasks = append(matchedTasks, task)
		matchedTasksByID[task.ID] = task
	}
	slices.SortStableFunc(matchedTasks, func(a, b Task) int { return a.Stage - b.Stage })
	for _, task := range matchedTasks {
		if task.Source == SourceTask {
			sourceBuildTask, ok := matchedTasksByID[task.SourceTask]
			if !ok {
				return nil, fmt.Errorf("任务 %s 的来源任务未匹配本次触发", task.Name)
			}
			if !task.SameTrigger(sourceBuildTask) {
				return nil, fmt.Errorf("任务 %s 与来源构建任务的触发条件必须相同", task.Name)
			}
		}
		if task.Action == ActionBuild {
			if _, err := reference.WithTag(mustRepository(), tag+task.TagSuffix); err != nil {
				return nil, fmt.Errorf("任务 %s 的目标 tag 无效", task.Name)
			}
			target := tag + task.TagSuffix
			if previous, ok := outputs[target]; ok && previous.Stage == task.Stage {
				return nil, errors.New("同阶段构建任务不能输出相同 tag")
			}
			outputs[target] = task
		}
		if task.Action == ActionDeploy {
			key := task.K8sConfig + "/" + task.K8sNamespace + "/" + task.K8sControllerType + "/" + task.K8sAppName
			for _, name := range strings.Split(task.K8sContainerName, ",") {
				k := "deploy:" + key + "/" + name
				if previous, ok := outputs[k]; ok && previous.Stage == task.Stage {
					return nil, errors.New("同阶段部署任务不能修改同一容器")
				}
				outputs[k] = task
			}
		}
	}
	return matchedTasks, nil
}
func mustRepository() reference.Named { name, _ := reference.WithName("workflow/image"); return name }
